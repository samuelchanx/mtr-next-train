#!/usr/bin/env python3
"""Generate data.js for the MTR Next Train web app from mtr_lines_and_stations.csv.

Source CSV: https://opendata.mtr.com.hk/data/mtr_lines_and_stations.csv
A local copy lives beside this script; re-run after refreshing the CSV:
    python3 build_data.py
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "mtr_lines_and_stations.csv")
OUT_PATH = os.path.join(HERE, "data.js")

# Lines covered by the Next Train API (Next_Train_API_Spec_v1.7)
API_LINES = ["AEL", "TCL", "TML", "TKL", "EAL", "SIL", "TWL", "ISL", "KTL", "DRL"]

LINE_META = {
    "AEL": ("機場快線", "Airport Express", "#00888A"),
    "TCL": ("東涌線", "Tung Chung Line", "#F7943E"),
    "TML": ("屯馬線", "Tuen Ma Line", "#923011"),
    "TKL": ("將軍澳線", "Tseung Kwan O Line", "#7D3F98"),
    "EAL": ("東鐵線", "East Rail Line", "#53B7E8"),
    "SIL": ("南港島線", "South Island Line", "#CBC092"),
    "TWL": ("荃灣線", "Tsuen Wan Line", "#ED1B24"),
    "ISL": ("港島線", "Island Line", "#007D80"),
    "KTL": ("觀塘線", "Kwun Tong Line", "#00A651"),
    "DRL": ("迪士尼線", "Disneyland Resort Line", "#F173AC"),
}

# Stations missing from MTR's own CSV but valid in the API (spec lists RAC; CSV omits it)
# code -> (tc, en, line, ut-seq)
EXTRA_STATIONS = {"RAC": ("馬場", "Racecourse", "EAL", 7.5)}


def main():
    with open(CSV_PATH, encoding="utf-8-sig") as f:
        rows = [r for r in csv.DictReader(f) if r["Line Code"]]

    stations = {}   # LINE -> [{c,tc,en,seq}] in display order
    termini = {}    # LINE -> {UP:{c,tc,en}, DOWN:{c,tc,en}}
    names = {}      # station code -> {tc,en} (global, for dest lookup)

    for code, (tc, en, _line, _seq) in EXTRA_STATIONS.items():
        names[code] = {"tc": tc, "en": en}

    for line in API_LINES:
        lrows = [r for r in rows if r["Line Code"] == line]
        main_rows = [r for r in lrows if r["Direction"] in ("UT", "DT")]
        ut = {r["Station Code"]: float(r["Sequence"]) for r in main_rows if r["Direction"] == "UT"}
        dt = {r["Station Code"]: float(r["Sequence"]) for r in main_rows if r["Direction"] == "DT"}

        # display order: main-line UT sequence; branch-only stations appended at the end
        branch = {}
        for r in lrows:
            c = r["Station Code"]
            if c not in ut and r["Direction"].endswith("UT"):
                branch[c] = float(r["Sequence"])
        seen, ordered = set(), []
        for c in sorted(ut, key=lambda c: ut[c]):
            ordered.append(c)
            seen.add(c)
        for c in sorted(branch, key=lambda c: branch[c]):
            if c not in seen:
                ordered.append(c)
                seen.add(c)
        for code, (tc, en, xline, xseq) in EXTRA_STATIONS.items():
            if xline == line and code not in seen:
                ordered.append(code)
                seen.add(code)

        st = {}
        max_main = max(ut.values()) if ut else 0
        for c in ordered:
            r = next((r for r in lrows if r["Station Code"] == c), None)
            if r is None:
                tc, en, _l, xseq = EXTRA_STATIONS[c]
                st[c] = {"c": c, "tc": tc, "en": en, "seq": xseq}
            else:
                seq = ut.get(c) or dt.get(c) or (max_main + branch.get(c, 0))
                st[c] = {"c": c, "tc": r["Chinese Name"], "en": r["English Name"], "seq": seq}
                names[c] = {"tc": r["Chinese Name"], "en": r["English Name"]}
        stations[line] = [st[c] for c in sorted(ordered, key=lambda c: st[c]["seq"])]

        def term(seq_map, pick):
            if not seq_map:
                return None
            c = pick(seq_map, key=lambda c: seq_map[c])
            r = next(r for r in lrows if r["Station Code"] == c)
            return {"c": c, "tc": r["Chinese Name"], "en": r["English Name"]}

        termini[line] = {
            "UP": term(ut, max) or term(dt, min),
            "DOWN": term(dt, max) or term(ut, min),
        }

    lines_js = [
        {"code": c, "tc": LINE_META[c][0], "en": LINE_META[c][1], "color": LINE_META[c][2]}
        for c in API_LINES
    ]

    payload = (
        "// Generated by build_data.py — do not edit by hand.\n"
        "const MTR_LINES = " + json.dumps(lines_js, ensure_ascii=False, indent=2) + ";\n\n"
        "const MTR_STATIONS = " + json.dumps(stations, ensure_ascii=False, indent=1) + ";\n\n"
        "const MTR_TERMINI = " + json.dumps(termini, ensure_ascii=False, indent=1) + ";\n\n"
        "const MTR_NAMES = " + json.dumps(names, ensure_ascii=False, indent=1) + ";\n"
    )
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(payload)

    total = sum(len(v) for v in stations.values())
    print(f"wrote {OUT_PATH}: {len(API_LINES)} lines, {total} station rows, {len(names)} unique station names")
    for line in API_LINES:
        up, down = termini[line]["UP"], termini[line]["DOWN"]
        print(f"  {line}: {len(stations[line])} stations | UP 往 {up['tc']} | DOWN 往 {down['tc']}")


if __name__ == "__main__":
    main()
